def main() -> int:
    parser = argparse.ArgumentParser(
        description="Run trigger evaluations across all packs"
    )
    parser.add_argument(
        "--eval-dir",
        default="evals/trigger",
        help="Directory containing eval JSON files (default: evals/trigger)",
    )
    parser.add_argument(
        "--packs-dir",
        default="packs",
        help="Path to packs directory for loading SKILL.md (default: packs)",
    )
    parser.add_argument(
        "--pack",
        default=None,
        help="Filter to a specific pack (substring match)",
    )
    parser.add_argument(
        "--variant",
        default="original",
        help="Label for this run variant (e.g. original, compressed). "
        "Used in output for A/B comparison.",
    )
    parser.add_argument(
        "--json",
        action="store_true",
        dest="json_output",
        help="Output results as JSON (for programmatic comparison)",
    )
    parser.add_argument(
        "--verbose",
        action="store_true",
        help="Show per-query scoring details",
    )
    parser.add_argument(
        "--threshold",
        type=float,
        default=TRIGGER_SCORE_THRESHOLD,
        help=f"Score threshold for trigger match (default: {TRIGGER_SCORE_THRESHOLD})",
    )
    args = parser.parse_args()

    eval_dir = Path(args.eval_dir).resolve()
    packs_dir = Path(args.packs_dir).resolve()

    if not eval_dir.is_dir():
        print(f"Eval directory not found: {eval_dir}", file=sys.stderr)
        print(
            "Run gen_trigger_evals.py first to generate eval datasets.", file=sys.stderr
        )
        return 2

    if not packs_dir.is_dir():
        print(f"Packs directory not found: {packs_dir}", file=sys.stderr)
        return 2

    evals = discover_evals(eval_dir, args.pack)
    if not evals:
        print("No eval files found.", file=sys.stderr)
        return 1

    print(f"Found {len(evals)} eval files, variant={args.variant}")

    results: list[dict] = []
    errors = 0

    for ev in evals:
        skill_md = find_skill_md(packs_dir, ev["pack"], ev["skill"])
        if not skill_md:
            if not args.json_output:
                print(f"  SKIP {ev['pack']}/{ev['skill']}: SKILL.md not found")
            errors += 1
            continue

        try:
            eval_data = json.loads(ev["eval_path"].read_text(encoding="utf-8"))
            skill_keywords = load_skill_keywords(skill_md)

            if args.verbose:
                print(f"\n  {ev['pack']}/{ev['skill']}:")

            result = evaluate_skill(
                eval_data,
                skill_keywords,
                threshold=args.threshold,
                verbose=args.verbose,
            )
            result["pack"] = ev["pack"]
            results.append(result)

        except Exception as exc:
            if not args.json_output:
                print(f"  ERROR {ev['pack']}/{ev['skill']}: {exc}", file=sys.stderr)
            errors += 1

    if args.json_output:
        output = {
            "variant": args.variant,
            "threshold": args.threshold,
            "total": len(results),
            "passed": sum(1 for r in results if r["verdict"] == "PASS"),
            "failed": sum(1 for r in results if r["verdict"] == "FAIL"),
            "errors": errors,
            "avg_trigger_pass_rate": round(
                sum(r["trigger_pass_rate"] for r in results) / len(results), 4
            )
            if results
            else 0,
            "avg_false_positive_rate": round(
                sum(r["false_positive_rate"] for r in results) / len(results), 4
            )
            if results
            else 0,
            "results": results,
        }
        print(json.dumps(output, indent=2, ensure_ascii=False))
    else:
        print_table(results)
        print_aggregate(results, args.variant)
        if errors:
            print(f"\n{errors} skill(s) skipped due to errors.")

    # Exit code: 0 if all pass, 1 if any fail
    any_fail = any(r["verdict"] == "FAIL" for r in results)
    return 1 if any_fail else 0


if __name__ == "__main__":
    raise SystemExit(main())

_CJK_RE = re.compile(r"[\u4e00-\u9fff\u3400-\u4dbf\uf900-\ufaff]")


# ---------------------------------------------------------------------------
# Keyword extraction & scoring (mirrored from evaluate_triggers.py)
# ---------------------------------------------------------------------------


def extract_keywords(text: str) -> set[str]:
    """Extract keywords from text, handling CJK via bigrams."""
    tokens: set[str] = set()
    text_lower = text.lower()
    for tok in re.findall(r"[a-z0-9_-]+", text_lower):
        if tok not in STOPWORDS and len(tok) > 1:
            tokens.add(tok)
    cjk_chars = _CJK_RE.findall(text)
    for i in range(len(cjk_chars) - 1):
        tokens.add(cjk_chars[i] + cjk_chars[i + 1])
    return tokens


def score_query(query: str, skill_keywords: set[str]) -> float:
    """Score a query against skill keywords. Returns max(recall, precision)."""
    query_kw = extract_keywords(query)
    if not query_kw or not skill_keywords:
        return 0.0
    overlap = query_kw & skill_keywords
    if not overlap:
        return 0.0
    precision = len(overlap) / len(query_kw)
    recall = len(overlap) / len(skill_keywords)
    return max(precision, recall)


# ---------------------------------------------------------------------------
# SKILL.md loader
# ---------------------------------------------------------------------------


def extract_frontmatter(text: str) -> dict:
    """Extract YAML-like frontmatter from SKILL.md, return metadata dict."""
    lines = text.split("\n")
    if not lines or lines[0].strip() != "---":
        return {}
    end_idx = -1
    for i, line in enumerate(lines[1:], 1):
        if line.strip() == "---":
            end_idx = i
            break
    if end_idx < 0:
        return {}
    meta: dict = {}
    current_key = ""
    current_val = ""
    for line in lines[1:end_idx]:
        if ":" in line and not line.startswith(" ") and not line.startswith("\t"):
            if current_key:
                meta[current_key] = current_val.strip()
            key, _, val = line.partition(":")
            current_key = key.strip()
            current_val = val.strip()
        else:
            current_val += " " + line.strip()
    if current_key:
        meta[current_key] = current_val.strip()
    return meta


def load_skill_keywords(skill_md_path: Path) -> set[str]:
    """Load a SKILL.md and return its description keywords."""
    text = skill_md_path.read_text(encoding="utf-8")
    meta = extract_frontmatter(text)
    description = meta.get("description", "")
    return extract_keywords(description)


# ---------------------------------------------------------------------------
# Eval runner
# ---------------------------------------------------------------------------


def evaluate_skill(
    eval_data: dict,
    skill_keywords: set[str],
    threshold: float = TRIGGER_SCORE_THRESHOLD,
    verbose: bool = False,
) -> dict:
    """Evaluate a single skill's trigger accuracy.

    Returns a result dict with per-query scores and aggregate metrics.
    """
    skill_name = eval_data.get("skill", "unknown")
    positives = eval_data.get("should_trigger", [])
    negatives = eval_data.get("should_not_trigger", [])

    pos_results = []
    for q in positives:
        s = score_query(q, skill_keywords)
        triggered = s >= threshold
        pos_results.append({"query": q, "score": round(s, 4), "triggered": triggered})
        if verbose:
            mark = "OK" if triggered else "MISS"
            print(f"    [+] {mark} ({s:.3f}) {q}")

    neg_results = []
    for q in negatives:
        s = score_query(q, skill_keywords)
        triggered = s >= threshold
        neg_results.append({"query": q, "score": round(s, 4), "triggered": triggered})
        if verbose:
            mark = "FP!" if triggered else "OK"
            print(f"    [-] {mark} ({s:.3f}) {q}")

    # Metrics
    pos_pass = sum(1 for r in pos_results if r["triggered"])
    pos_total = len(pos_results)
    neg_fp = sum(1 for r in neg_results if r["triggered"])
    neg_total = len(neg_results)

    trigger_pass_rate = pos_pass / pos_total if pos_total else 0.0
    false_positive_rate = neg_fp / neg_total if neg_total else 0.0

    # Verdict: pass_rate >= 0.80 AND fp_rate <= 0.15
    verdict = (
        "PASS" if trigger_pass_rate >= 0.80 and false_positive_rate <= 0.15 else "FAIL"
    )

    return {
        "skill": skill_name,
        "trigger_pass_rate": round(trigger_pass_rate, 4),
        "false_positive_rate": round(false_positive_rate, 4),
        "positive_passed": pos_pass,
        "positive_total": pos_total,
        "negative_false_positives": neg_fp,
        "negative_total": neg_total,
        "verdict": verdict,
        "positive_details": pos_results,
        "negative_details": neg_results,
    }


# ---------------------------------------------------------------------------
# Discovery: find eval files and match to SKILL.md
# ---------------------------------------------------------------------------


def discover_evals(eval_dir: Path, pack_filter: str | None = None) -> list[dict]:
    """Discover eval JSON files. Returns list of {pack, skill, eval_path}."""
    evals = []
    if not eval_dir.is_dir():
        return evals

    for pack_dir in sorted(eval_dir.iterdir()):
        if not pack_dir.is_dir():
            continue
        if pack_filter and pack_filter not in pack_dir.name:
            continue
        for eval_file in sorted(pack_dir.glob("*.json")):
            evals.append(
                {
                    "pack": pack_dir.name,
                    "skill": eval_file.stem,
                    "eval_path": eval_file,
                }
            )
    return evals


def find_skill_md(packs_dir: Path, pack_name: str, skill_name: str) -> Path | None:
    """Find the SKILL.md for a given pack/skill combo."""
    # Try exact pack directory name first
    for pack_dir in packs_dir.iterdir():
        if not pack_dir.is_dir():
            continue
        if pack_name not in pack_dir.name:
            continue
        skill_md = pack_dir / ".opencode" / "skills" / skill_name / "SKILL.md"
        if skill_md.is_file():
            return skill_md
    return None


# ---------------------------------------------------------------------------
# Report
# ---------------------------------------------------------------------------


def print_table(results: list[dict]) -> None:
    """Print a human-readable results table."""
    # Header
    print(f"\n{'Pack':<35} {'Skill':<35} {'Pass%':>6} {'FP%':>6} {'Verdict':>8}")
    print("-" * 95)

    for r in results:
        pack = r.get("pack", "?")
        skill = r["skill"]
        pr = f"{r['trigger_pass_rate']:.0%}"
        fp = f"{r['false_positive_rate']:.0%}"
        v = r["verdict"]
        print(f"{pack:<35} {skill:<35} {pr:>6} {fp:>6} {v:>8}")


def print_aggregate(results: list[dict], variant: str) -> None:
    """Print aggregate statistics."""
    total = len(results)
    passed = sum(1 for r in results if r["verdict"] == "PASS")
    failed = total - passed

    avg_pass_rate = sum(r["trigger_pass_rate"] for r in results) / total if total else 0
    avg_fp_rate = sum(r["false_positive_rate"] for r in results) / total if total else 0

    print(f"\n{'=' * 50}")
    print(f"Variant: {variant}")
    print(f"Total skills: {total}")
    print(f"PASS: {passed}  FAIL: {failed}")
    print(f"Avg trigger pass rate: {avg_pass_rate:.1%}")
    print(f"Avg false positive rate: {avg_fp_rate:.1%}")
    print(f"Overall: {'PASS' if failed == 0 else 'FAIL'}")
    print(f"{'=' * 50}")


